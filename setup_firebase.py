# CONFIG VALIDATOR
# ============================================================
def validate_config():
    """Validate the current firebase-config.js file."""
    print(f"\n{Colors.BOLD}🔍 Config Validator{Colors.END}")
    print("=" * 50)

    config_path = Path("js/firebase-config.js")
    if not config_path.exists():
        print_error("js/firebase-config.js not found!")
        print_info("Run: python setup_firebase.py --generate-config")
        return False

    content = config_path.read_text()
    errors = []

    # Check Firebase placeholders
    firebase_placeholders = ["YOUR_API_KEY", "YOUR_PROJECT_ID", "YOUR_MESSAGING_SENDER_ID", "YOUR_APP_ID"]
    for p in firebase_placeholders:
        if p in content:
            errors.append(f"Firebase placeholder found: {p}")

    # Check Cloudinary placeholders
    cloudinary_placeholders = ["YOUR_CLOUD_NAME", "YOUR_UPLOAD_PRESET"]
    for p in cloudinary_placeholders:
        if p in content:
            errors.append(f"Cloudinary placeholder found: {p}")

    if errors:
        for e in errors:
            print_error(e)
        print()
        print_warning("Config me placeholder values hain!")
        print_info("Run: python setup_firebase.py --generate-config")
        return False

    # Validate format
    cloud_name_match = re.search(r'cloudName:\s*"(.+?)"', content)
    project_id_match = re.search(r'projectId:\s*"(.+?)"', content)
    preset_match = re.search(r'uploadPreset:\s*"(.+?)"', content)

    if cloud_name_match and project_id_match and preset_match:
        print_success("Config format is valid!")
        print_info(f"Firebase Project: {project_id_match.group(1)}")
        print_info(f"Cloudinary Cloud: {cloud_name_match.group(1)}")
        print_info(f"Upload Preset: {preset_match.group(1)}")
        return True
    else:
        print_error("Could not parse all config values")
        return False


