# VERCEL DEPLOYMENT
# ============================================================
def check_vercel_cli():
    """Check if Vercel CLI is installed."""
    try:
        result = subprocess.run(["vercel", "--version"], capture_output=True, text=True)
        return result.returncode == 0
    except FileNotFoundError:
        return False


def deploy_to_vercel(production=False):
    """Deploy the app to Vercel."""
    print(f"\n{Colors.BOLD}🚀 Vercel Deployment{Colors.END}")
    print("=" * 50)

    if not check_vercel_cli():
        print_error("Vercel CLI not found!")
        print()
        print_info("Install Vercel CLI:")
        print(f"  {Colors.CYAN}npm install -g vercel{Colors.END}")
        print()
        print_info("Or deploy manually:")
        print(f"  1. Go to {Colors.CYAN}https://vercel.com/new{Colors.END}")
        print(f"  2. Import your GitHub repo: {Colors.CYAN}AAKASH-CODES-CODE/Photos{Colors.END}")
        print(f"  3. Framework Preset: {Colors.CYAN}Other{Colors.END}")
        print(f"  4. Root Directory: {Colors.CYAN}./{Colors.END}")
        print(f"  5. Click {Colors.GREEN}Deploy{Colors.END}")
        return False

    # Validate config first
    if not validate_config():
        print()
        print_warning("Fix your Firebase config before deploying!")
        response = input(f"{Colors.CYAN}Deploy anyway? (y/N): {Colors.END}").strip().lower()
        if response != 'y':
            return False

    cmd = ["vercel", "--prod"] if production else ["vercel"]
    mode = "Production" if production else "Preview"

    print_info(f"Deploying to Vercel ({mode})...")
    print()

    try:
        result = subprocess.run(cmd, capture_output=False)
        if result.returncode == 0:
            print()
            print_success(f"Deployed to Vercel ({mode})!")
            return True
        else:
            print_error("Deployment failed. Check the errors above.")
            return False
    except Exception as e:
        print_error(f"Error: {e}")
        return False


