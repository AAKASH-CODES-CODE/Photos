# FULL SETUP WIZARD
# ============================================================
def full_setup():
    """Run the complete setup wizard."""
    print_banner()

    print(f"{Colors.BOLD}What would you like to do?{Colors.END}")
    print()
    print("  1. 🔧 Generate Firebase Config (interactive)")
    print("  2. 🔐 Generate Security Rules")
    print("  3. ✅ Validate Current Config")
    print("  4. 🚀 Deploy to Vercel (Preview)")
    print("  5. 🌐 Deploy to Vercel (Production)")
    print("  6. 📦 Full Setup (Config + Rules + Deploy)")
    print("  7. ❌ Exit")
    print()

    choice = input(f"{Colors.CYAN}Enter your choice (1-7): {Colors.END}").strip()

    if choice == "1":
        generate_firebase_config()
    elif choice == "2":
        generate_all_rules()
    elif choice == "3":
        validate_config()
    elif choice == "4":
        deploy_to_vercel(production=False)
    elif choice == "5":
        deploy_to_vercel(production=True)
    elif choice == "6":
        print_info("Starting full setup...")
        if generate_firebase_config():
            generate_all_rules()
            print()
            response = input(f"{Colors.CYAN}Deploy to Vercel now? (y/N): {Colors.END}").strip().lower()
            if response == 'y':
                deploy_to_vercel(production=True)
    elif choice == "7":
        print_info("Goodbye!")
        sys.exit(0)
    else:
        print_error("Invalid choice. Please enter 1-7.")


# ============================================================
# CLI ARGUMENTS
# ============================================================
def main():
    """Main entry point with CLI argument support."""
    if len(sys.argv) > 1:
        arg = sys.argv[1]

        if arg in ("--generate-config", "-c"):
            print_banner()
            generate_firebase_config()
        elif arg in ("--generate-rules", "-r"):
            print_banner()
            generate_all_rules()
        elif arg in ("--validate", "-v"):
            print_banner()
            validate_config()
        elif arg in ("--deploy", "-d"):
            print_banner()
            deploy_to_vercel(production=True)
        elif arg in ("--deploy-preview", "-p"):
            print_banner()
            deploy_to_vercel(production=False)
        elif arg in ("--help", "-h"):
            print_banner()
            print(f"{Colors.BOLD}Available Commands:{Colors.END}")
            print()
            print(f"  {Colors.CYAN}python setup_firebase.py{Colors.END}              Interactive wizard")
            print(f"  {Colors.CYAN}python setup_firebase.py --generate-config{Colors.END}  Generate Firebase config")
            print(f"  {Colors.CYAN}python setup_firebase.py --generate-rules{Colors.END}   Generate security rules")
            print(f"  {Colors.CYAN}python setup_firebase.py --validate{Colors.END}         Validate config")
            print(f"  {Colors.CYAN}python setup_firebase.py --deploy{Colors.END}           Deploy to Vercel (prod)")
            print(f"  {Colors.CYAN}python setup_firebase.py --deploy-preview{Colors.END}   Deploy to Vercel (preview)")
            print()
            print(f"  {Colors.CYAN}Short flags: -c, -r, -v, -d, -p, -h{Colors.END}")
        else:
            print_error(f"Unknown argument: {arg}")
            print_info("Use --help for available commands")
    else:
        full_setup()


if __name__ == "__main__":
    main()
