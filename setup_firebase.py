# VERCEL DEPLOYMENT
# ============================================================
def check_vercel_cli():
    try:
        result = subprocess.run(["vercel", "--version"], capture_output=True, text=True)
        return result.returncode == 0
    except FileNotFoundError:
        return False


def deploy_to_vercel(production=False):
    """Deploy the app to Vercel."""
    print(f"\n{Colors.BOLD}🚀 Vercel Deployment{Colors.END}")
    print("=" * 50)

    if not check_vercel_cli():
        print_error("Vercel CLI not found!")
        print()
        print_info("Install karo:")
        print(f"   {Colors.CYAN}npm install -g vercel{Colors.END}")
        print()
        print_info("Ya manually deploy karo:")
        print(f"   1. {Colors.CYAN}https://vercel.com/new{Colors.END} pe jao")
        print(f"   2. GitHub repo import karo")
        print(f"   3. Framework: {Colors.CYAN}Other{Colors.END}")
        print(f"   4. {Colors.GREEN}Deploy{Colors.END} click karo")
        return False

    if not validate_config():
        print()
        response = input(f"{Colors.CYAN}Config incomplete hai. Phir bhi deploy kare? (y/N): {Colors.END}").strip().lower()
        if response != 'y':
            return False

    cmd = ["vercel", "--prod"] if production else ["vercel"]
    mode = "Production" if production else "Preview"

    print_info(f"Deploying ({mode})...")
    print()

    try:
        result = subprocess.run(cmd)
        if result.returncode == 0:
            print()
            print_success(f"Vercel deploy successful ({mode})! 🎉")
            return True
        else:
            print_error("Deployment failed.")
            return False
    except Exception as e:
        print_error(f"Error: {e}")
        return False


