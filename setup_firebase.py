# CONFIG VALIDATOR
# ============================================================
def validate_config():
    """Validate the current firebase-config.js file."""
    print(f"\n{Colors.BOLD}🔍 Config Validator{Colors.END}")
    print("=" * 50)

    config_path = Path("js/firebase-config.js")
    if not config_path.exists():
        print_error("js/firebase-config.js not found!")
        print_info("Run: python setup_firebase.py --generate-config")
        return False

    content = config_path.read_text()

    # Check for placeholder values
    placeholders = ["YOUR_API_KEY", "YOUR_PROJECT_ID", "YOUR_MESSAGING_SENDER_ID", "YOUR_APP_ID"]
    has_placeholders = False

    for placeholder in placeholders:
        if placeholder in content:
            print_error(f"Found placeholder: {placeholder}")
            has_placeholders = True

    if has_placeholders:
        print()
        print_warning("Config still has placeholder values!")
        print_info("Run: python setup_firebase.py --generate-config")
        return False

    # Validate format
    api_key_match = re.search(r'apiKey:\s*"(.+?)"', content)
    project_id_match = re.search(r'projectId:\s*"(.+?)"', content)

    if api_key_match and project_id_match:
        print_success("Config format is valid")
        print_info(f"Project ID: {project_id_match.group(1)}")
        print_info(f"API Key: {api_key_match.group(1)[:10]}...")
        return True
    else:
        print_error("Could not parse config values")
        return False


