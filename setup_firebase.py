# SECURITY RULES GENERATOR
# ============================================================
def generate_firestore_rules():
    """Generate Firestore security rules file."""
    rules = '''rules_version = '2';
service cloud.firestore {
  match /databases/{database}/documents {

    // Media collection - users can only access their own photos
    match /media/{document} {
      allow read: if request.auth != null && resource.data.userId == request.auth.uid;
      allow create: if request.auth != null && request.resource.data.userId == request.auth.uid;
      allow update, delete: if request.auth != null && resource.data.userId == request.auth.uid;
    }

    // Folders collection - users can only access their own albums
    match /folders/{document} {
      allow read: if request.auth != null && resource.data.userId == request.auth.uid;
      allow create: if request.auth != null && request.resource.data.userId == request.auth.uid;
      allow update, delete: if request.auth != null && resource.data.userId == request.auth.uid;
    }
  }
}
'''
    rules_path = Path("firestore.rules")
    rules_path.write_text(rules)
    print_success(f"Firestore rules written to: {rules_path}")
    return rules_path


def generate_storage_rules():
    """Generate Firebase Storage security rules file."""
    rules = '''rules_version = '2';
service firebase.storage {
  match /b/{bucket}/o {
    // Users can only read/write to their own folder
    match /users/{userId}/{allPaths=**} {
      allow read, write: if request.auth != null && request.auth.uid == userId;
    }
  }
}
'''
    rules_path = Path("storage.rules")
    rules_path.write_text(rules)
    print_success(f"Storage rules written to: {rules_path}")
    return rules_path


def generate_all_rules():
    """Generate both Firestore and Storage rules."""
    print(f"\n{Colors.BOLD}🔐 Security Rules Generator{Colors.END}")
    print("=" * 50)
    generate_firestore_rules()
    generate_storage_rules()
    print()
    print_info("Copy these rules to Firebase Console:")
    print(f"  • Firestore: Firebase Console > Firestore > Rules")
    print(f"  • Storage:   Firebase Console > Storage > Rules")


